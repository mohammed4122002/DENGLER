/** Stable, human-readable ids — no randomness, so SSR and client agree. */
const id = (prefix: string, n: number) => `${prefix}_${String(n).padStart(3, "0")}`;

/** Deterministic timestamps so the demo catalogue never churns between renders. */
const EPOCH = Date.UTC(2025, 0, 6);
const at = (daysAgo: number) =>
  new Date(EPOCH - daysAgo * 86_400_000).toISOString();

function build(raw: RawProperty, index: number): Property {
  const propertyId = id("prop", index + 1);
  const created = at(RAW.length - index);

  return {
    id: propertyId,
    title: raw.title,
    slug: raw.slug,
    description: raw.description,
    property_type: raw.type,
    status: raw.status ?? "available",
    price: raw.price,
    currency: raw.currency ?? "USD",
    location: raw.location,
    country: raw.country,
    city: raw.city,
    latitude: raw.lat,
    longitude: raw.lng,
    area: raw.area,
    bedrooms: raw.beds ?? null,
    bathrooms: raw.baths ?? null,
    year_built: raw.built ?? null,
    investment_type: raw.investment,
    roi: raw.roi ?? null,
    annual_revenue: raw.revenue ?? null,
    occupancy_rate: raw.occupancy ?? null,
    appreciation: raw.appreciation ?? null,
    featured: raw.featured ?? false,
    published: true,
    cover_image: photo(raw.cover, 1600),
    tagline: raw.tagline,
    created_at: created,
    updated_at: created,
    images: [raw.cover, ...raw.gallery].map((key, i) => ({
      id: `${propertyId}_img_${i}`,
      property_id: propertyId,
      image_url: photo(key, 1800),
      alt: `${raw.title} — view ${i + 1}`,
      sort_order: i,
      created_at: created,
    })),
    features: raw.features,
  };
}

